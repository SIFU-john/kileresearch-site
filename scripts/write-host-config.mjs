// Writes host-specific header files from config/security-headers.mjs. Runs after `astro build`.
import { writeFile, mkdir } from 'node:fs/promises';
import { securityHeaders, cacheRules } from '../config/security-headers.mjs';

const headers = securityHeaders();

// Netlify / Cloudflare Pages
const lines = ['/*', ...Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`), ''];
for (const r of cacheRules.filter((r) => r.pattern !== '/*')) lines.push(r.pattern, `  Cache-Control: ${r.value}`, '');
await writeFile('dist/_headers', lines.join('\n'));

// AWS CloudFront ResponseHeadersPolicyConfig (aws cloudfront create-response-headers-policy --response-headers-policy-config file://...)
const sts = /max-age=(\d+)/.exec(headers['Strict-Transport-Security'])[1];
const custom = ['Permissions-Policy', 'Cross-Origin-Opener-Policy', 'Cross-Origin-Resource-Policy', 'X-Permitted-Cross-Domain-Policies'];
const policy = {
  Name: 'kile-research-security-headers',
  Comment: 'Generated by scripts/write-host-config.mjs. Do not edit by hand.',
  SecurityHeadersConfig: {
    ContentSecurityPolicy: { Override: true, ContentSecurityPolicy: headers['Content-Security-Policy'] },
    StrictTransportSecurity: { Override: true, AccessControlMaxAgeSec: Number(sts), IncludeSubdomains: true, Preload: true },
    ContentTypeOptions: { Override: true },
    FrameOptions: { Override: true, FrameOption: 'DENY' },
    ReferrerPolicy: { Override: true, ReferrerPolicy: 'strict-origin-when-cross-origin' },
  },
  CustomHeadersConfig: {
    Quantity: custom.length,
    Items: custom.map((h) => ({ Header: h, Value: headers[h], Override: true })),
  },
};
await mkdir('infra', { recursive: true });
await writeFile('infra/cloudfront-response-headers-policy.json', JSON.stringify(policy, null, 2) + '\n');
console.log('wrote dist/_headers and infra/cloudfront-response-headers-policy.json');
